# 功能: 语料层之二 —— 平台语体骨架、行业语境槽位、反向观点池、账号池、后缀池。
#
# 真实感的三条设计原则：
#   1) 平台语体分化：微博是碎片抱怨，抖音是短句外放，知乎是分点长文，
#      新闻门户是记者报道体，论坛是从业者长贴 —— 同一个事件在不同平台的说法本就不同。
#   2) 长文骨架必须「行业脱敏」：长文里天然会讲到组织体系、责任划分、利益分配，
#      这些内容在不同行业下都成立。因此把行业语境全部
#      槽位化（{org}/{unit}/{metric}/{blame_line}/{profit_src}…），由 BIZ_BY_EVENT
#      按事件注入，彻底修掉跨行业串料。
#   3) 情感词内建：分析引擎会用自己的词典对正文重新打分，所以每条骨架都要主动
#      带上对应情感词（离谱/无语/失望/寒心/担心/质疑…），否则文本与标注情感会对不上。
